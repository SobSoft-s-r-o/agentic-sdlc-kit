/**
 * The plan/apply/uninstall engine. `planApply` and `planUninstall` only read (through the injected
 * `RepoFs`) and describe what would change; `applyPlan` is the one place that writes.
 *
 * What the kit may touch is decided by the install manifest: a region is "ours" when the manifest
 * has an entry for it, "unmodified" while its content on disk still hashes to that entry, and
 * "modified locally" once it does not. Modified regions are kept and reported, never overwritten,
 * unless the caller passes `overwriteModified`. Whatever is not in the manifest is the user's.
 */

import type { Change } from '../render/changes.js';
import {
  MANIFEST_PATH,
  canonicalJson,
  entryDiskHash,
  hashText,
  newManifest,
  serializeManifest,
  sortEntries,
  type Manifest,
  type ManifestEntry,
} from './manifest.js';
import {
  assertJsonPointer,
  blockBody,
  canonicalBody,
  filterTomlBody,
  jsonKey,
  jsonValueAt,
  mergeJsonKeys,
  mergeLineBlock,
  mergeMdBlock,
  mergeTomlBlock,
  parseJsonObject,
  removeJsonKeys,
  removeLineBlock,
  removeMdBlock,
  removeTomlBlock,
  tomlTableText,
  type BlockKind,
  type JsonEntry,
} from './merge.js';
import type { RepoFs } from './repoFs.js';

export interface Notice {
  path: string;
  message: string;
}

export interface PlanError {
  path: string;
  message: string;
}

export interface PlannedWrite {
  path: string;
  action: 'create' | 'update' | 'remove';
  /** The whole file text for `create` and `update`. */
  content?: string;
  mode?: 0o755;
  /** The manifest entries this path had before; restored if the write fails so a retry still finds them. */
  previous?: ManifestEntry[];
}

export interface ApplyPlan {
  writes: PlannedWrite[];
  notices: Notice[];
  errors: PlanError[];
  /** Manifest entries that no change produces any more (a harness or server was dropped from the config). */
  obsolete: ManifestEntry[];
  /**
   * The manifest after the planned writes: entries for everything the changes produce, plus the
   * entries of regions that were kept as modified. Obsolete entries are not in it; `applyPlan`
   * puts them back unless it removes them.
   */
  manifest: Manifest;
}

export interface ApplyResult {
  /** Paths written, without the manifest. */
  written: string[];
  /** Paths removed (files, never directories), without the manifest. */
  removed: string[];
  /** The plan's notices plus the ones raised while removing obsolete entries. */
  notices: Notice[];
  /** Plan errors plus failed writes. A command exits 1 when this is not empty. */
  errors: PlanError[];
  manifest: Manifest;
}

const MODIFIED_KEPT = 'modified locally; kept';
const MODIFIED = `${MODIFIED_KEPT} (rerun with --overwrite-modified to replace)`;
const UNMANAGED = 'exists, not managed by sdlc; kept';
const OBSOLETE_MODIFIED = 'no longer generated by sdlc and modified locally; kept';
const NO_LONGER_GENERATED = 'no longer generated';

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
const messageOf = (error: unknown): string => (error instanceof Error ? error.message : String(error));
const identity = (e: ManifestEntry): string => [e.path, e.kind, e.key ?? ''].join('\u0000');

// --- planApply ------------------------------------------------------------------------------------

interface Planned {
  write?: PlannedWrite;
  notices: Notice[];
  /** The entries this change leaves in the manifest: new ones, and old ones for regions it kept. */
  entries: ManifestEntry[];
}

interface Context {
  fs: RepoFs;
  prior: ManifestEntry[];
  overwriteModified: boolean;
}

export function planApply(
  changes: Change[],
  fs: RepoFs,
  manifest: Manifest | undefined,
  opts: { overwriteModified: boolean },
): ApplyPlan {
  const previous = manifest?.entries ?? [];
  const priorByPath = groupByPath(previous);
  const writes: PlannedWrite[] = [];
  const notices: Notice[] = [];
  const errors: PlanError[] = [];
  const entries: ManifestEntry[] = [];
  const produced = new Set<string>();
  const keep = (list: ManifestEntry[]): void => {
    for (const entry of list) {
      entries.push(entry);
      produced.add(identity(entry));
    }
  };

  const count = new Map<string, number>();
  for (const change of changes) count.set(change.path, (count.get(change.path) ?? 0) + 1);
  const failed = new Set<string>();

  for (const change of [...changes].sort((a, b) => compare(a.path, b.path))) {
    const prior = priorByPath.get(change.path) ?? [];
    if (failed.has(change.path)) continue;
    if ((count.get(change.path) ?? 0) > 1) {
      failed.add(change.path);
      errors.push({ path: change.path, message: `more than one change targets ${change.path}` });
      keep(prior);
      continue;
    }
    try {
      const planned = planChange(change, { fs, prior, overwriteModified: opts.overwriteModified });
      if (planned.write) writes.push(planned.write);
      notices.push(...planned.notices);
      keep(planned.entries);
    } catch (error) {
      // The file is left exactly as it is, and the kit keeps its claim on what it had written there.
      errors.push({ path: change.path, message: messageOf(error) });
      keep(prior);
    }
  }

  const changePaths = new Set(changes.map(c => c.path));
  const tomlPaths = new Set(changes.filter(c => c.kind === 'toml-block').map(c => c.path));
  const obsolete = sortEntries(
    previous.filter(
      e =>
        !produced.has(identity(e)) &&
        // per-table TOML entries only describe the block; they go when the block's entry does
        !(e.kind === 'toml-block' && e.key !== undefined) &&
        // the TOML change still targets this path: a block it dropped (every table is now the user's) is not obsolete
        !(e.kind === 'toml-block' && tomlPaths.has(e.path)) &&
        // the path is now produced as something else; do not delete it from under that change
        !(e.kind === 'file' && changePaths.has(e.path)),
    ),
  );

  return {
    writes: writes.sort((a, b) => compare(a.path, b.path)),
    notices,
    errors,
    manifest: newManifest(entries),
    obsolete,
  };
}

function groupByPath(entries: ManifestEntry[]): Map<string, ManifestEntry[]> {
  const grouped = new Map<string, ManifestEntry[]>();
  for (const entry of entries) {
    const list = grouped.get(entry.path);
    if (list) list.push(entry);
    else grouped.set(entry.path, [entry]);
  }
  return grouped;
}

function planChange(change: Change, ctx: Context): Planned {
  const disk = ctx.fs.read(change.path);
  switch (change.kind) {
    case 'file':
      return planFile(change.path, change.content, change.mode, disk, ctx);
    case 'md-block':
      return planBlock(change.path, 'md-block', canonicalBody(change.content), disk, ctx, d =>
        mergeMdBlock(d, change.content),
      );
    case 'line-block':
      return planBlock(change.path, 'line-block', canonicalBody(change.content), disk, ctx, d =>
        mergeLineBlock(d, change.content),
      );
    case 'json-keys':
      return planJson(change.path, change.entries, disk, ctx);
    case 'toml-block':
      return planToml(change.path, change.content, change.ownedTables, disk, ctx);
  }
}

const put = (
  ctx: Context,
  path: string,
  disk: string | undefined,
  content: string,
  mode?: 0o755,
): PlannedWrite => ({
  path,
  action: disk === undefined ? 'create' : 'update',
  content,
  ...(mode === undefined ? {} : { mode }),
  ...(ctx.prior.length === 0 ? {} : { previous: ctx.prior }),
});

function planFile(
  path: string,
  content: string,
  mode: 0o755 | undefined,
  disk: string | undefined,
  ctx: Context,
): Planned {
  const desired = hashText(content);
  const fresh: ManifestEntry = { path, kind: 'file', hash: desired };
  const own = ctx.prior.find(e => e.kind === 'file');

  if (disk === undefined) return { write: put(ctx, path, disk, content, mode), notices: [], entries: [fresh] };
  const onDisk = hashText(disk);
  // Identical to what we would write: it costs the user nothing to take it over, silently.
  if (onDisk === desired) return { notices: [], entries: [fresh] };
  if (!own) return { notices: [{ path, message: UNMANAGED }], entries: [] };
  if (onDisk === own.hash || ctx.overwriteModified) {
    return { write: put(ctx, path, disk, content, mode), notices: [], entries: [fresh] };
  }
  return { notices: [{ path, message: MODIFIED }], entries: [own] };
}

/** Plans one marker-delimited block; `body` is already canonical and `build` produces the new file text. */
function planBlock(
  path: string,
  kind: BlockKind,
  body: string,
  disk: string | undefined,
  ctx: Context,
  build: (disk: string | undefined) => string,
): Planned & { kept: boolean } {
  const fresh: ManifestEntry = { path, kind, hash: hashText(body) };
  const own = ctx.prior.find(e => e.kind === kind && e.key === undefined);
  const write = (): Planned & { kept: boolean } => {
    const text = build(disk);
    return {
      ...(text === disk ? {} : { write: put(ctx, path, disk, text) }),
      notices: [],
      entries: [fresh],
      kept: false,
    };
  };
  const kept = (): Planned & { kept: boolean } => ({
    notices: [{ path, message: MODIFIED }],
    entries: own ? [own] : [],
    kept: true,
  });

  const current = disk === undefined ? undefined : blockBody(disk, kind);
  if (disk === undefined) return write();
  if (current === undefined) {
    // The file has no markers. Markers that vanished from a file we had written to were removed by the user.
    return own && !ctx.overwriteModified ? kept() : write();
  }
  const onDisk = hashText(current);
  if (onDisk === fresh.hash) return { notices: [], entries: [fresh], kept: false };
  if ((own && onDisk === own.hash) || ctx.overwriteModified) return write();
  return kept();
}

function planToml(
  path: string,
  content: string,
  ownedTables: string[],
  disk: string | undefined,
  ctx: Context,
): Planned {
  const { body, skipped } = filterTomlBody(disk, content, ownedTables);
  const skippedNotices = skipped.map(table => ({ path, message: `${table} already defined by you; kept` }));
  if (body === '') return planStaleToml(path, disk, ctx, skippedNotices);

  const planned = planBlock(path, 'toml-block', body, disk, ctx, d => mergeTomlBlock(d, content, ownedTables).text);
  // A kept block keeps the per-table entries it had; a written or unchanged one gets fresh ones.
  const tables: ManifestEntry[] = planned.kept
    ? planned.entries.length === 0
      ? []
      : ctx.prior.filter(e => e.kind === 'toml-block' && e.key !== undefined)
    : ownedTables.flatMap(table => {
        const text = tomlTableText(body, table);
        return text === undefined ? [] : [{ path, kind: 'toml-block' as const, key: table, hash: hashText(text) }];
      });
  return {
    ...(planned.write ? { write: planned.write } : {}),
    notices: [...planned.notices, ...skippedNotices],
    entries: [...planned.entries, ...tables],
  };
}

/**
 * Every table of the block is now the user's (they define them outside it). Nothing is left to
 * manage, but a block we wrote earlier would redefine those tables, so it goes under the usual
 * rules: removed while it is unmodified (or with `overwriteModified`), kept and reported when the
 * user edited it. A file left with nothing in it is deleted.
 */
function planStaleToml(path: string, disk: string | undefined, ctx: Context, skippedNotices: Notice[]): Planned {
  const current = disk === undefined ? undefined : blockBody(disk, 'toml-block');
  if (disk === undefined || current === undefined) return { notices: skippedNotices, entries: [] };

  const own = ctx.prior.find(e => e.kind === 'toml-block' && e.key === undefined);
  if ((own && hashText(current) === own.hash) || ctx.overwriteModified) {
    const text = removeTomlBlock(disk);
    const previous = ctx.prior.length === 0 ? {} : { previous: ctx.prior };
    const write: PlannedWrite =
      text === '' ? { path, action: 'remove', ...previous } : { path, action: 'update', content: text, ...previous };
    return { write, notices: skippedNotices, entries: [] };
  }
  return {
    notices: [{ path, message: MODIFIED }, ...skippedNotices],
    entries: own ? ctx.prior.filter(e => e.kind === 'toml-block') : [],
  };
}

function planJson(path: string, jsonEntries: JsonEntry[], disk: string | undefined, ctx: Context): Planned {
  for (const item of jsonEntries) assertJsonPointer(item.pointer, path);
  const root = parseJsonObject(disk, path);
  // The kit created this file (now, or on an earlier run): uninstall may then clean up after itself.
  const created = disk === undefined || ctx.prior.some(e => e.kind === 'json-keys' && e.createdFile === true);
  const stamp = (e: ManifestEntry): ManifestEntry => (created ? { ...e, createdFile: true } : e);
  const owned = new Set<string>();
  const toMerge: JsonEntry[] = [];
  const entries: ManifestEntry[] = [];
  const notices: Notice[] = [];
  let changesSomething = false;

  for (const item of jsonEntries) {
    const key = jsonKey(item.pointer);
    const fresh: ManifestEntry = { path, kind: 'json-keys', key, hash: hashText(canonicalJson(item.value)) };
    const own = ctx.prior.find(e => e.kind === 'json-keys' && e.key === key);
    const current = jsonValueAt(root, item.pointer);
    const modified = (): void => {
      notices.push({ path, message: `${key}: ${MODIFIED}` });
      if (own) entries.push(own);
    };

    if (!current.found) {
      // A server we wrote that is gone was removed by the user, unless the whole file is gone.
      if (own && disk !== undefined && !ctx.overwriteModified) modified();
      else {
        toMerge.push(item);
        changesSomething = true;
        entries.push(fresh);
      }
    } else if (!own) {
      // A value equal to ours is taken over silently; any other one is the user's (the merge reports it).
      if (hashText(canonicalJson(current.value)) === fresh.hash) entries.push(fresh);
      else toMerge.push(item);
    } else {
      const onDisk = hashText(canonicalJson(current.value));
      if (onDisk === fresh.hash) entries.push(fresh);
      else if (onDisk === own.hash || ctx.overwriteModified) {
        owned.add(key);
        toMerge.push(item);
        changesSomething = true;
        entries.push(fresh);
      } else modified();
    }
  }

  const stamped = entries.map(stamp);
  if (toMerge.length === 0) return { notices, entries: stamped };
  const merged = mergeJsonKeys(disk, toMerge, owned, path);
  for (const key of merged.skipped) notices.push({ path, message: `${key} already defined by you; kept` });
  const write = changesSomething && merged.text !== disk ? put(ctx, path, disk, merged.text) : undefined;
  return { ...(write ? { write } : {}), notices, entries: stamped };
}

// --- removals (obsolete entries and uninstall) ----------------------------------------------------

interface RemovalPlan {
  writes: PlannedWrite[];
  notices: Notice[];
  errors: PlanError[];
  /** Entries of files that could not be read or merged; they stay in the manifest. */
  carried: ManifestEntry[];
}

/**
 * Plans the removal of the given entries from what is on disk now. A region whose content still
 * hashes to its entry is removed; a modified one is kept with `modifiedMessage`; one that is already
 * gone is ignored. A file that ends up empty is deleted, and so is a JSON file the kit created that
 * ends up as `{}`.
 */
function planRemovals(entries: ManifestEntry[], fs: RepoFs, modifiedMessage: string): RemovalPlan {
  const plan: RemovalPlan = { writes: [], notices: [], errors: [], carried: [] };
  // per-table TOML entries are covered by the entry of their block
  const grouped = groupByPath(entries.filter(e => !(e.kind === 'toml-block' && e.key !== undefined)));

  for (const path of [...grouped.keys()].sort(compare)) {
    const group = grouped.get(path) ?? [];
    try {
      const disk = fs.read(path);
      if (disk === undefined) continue;

      const removable: ManifestEntry[] = [];
      for (const entry of group) {
        const current = entryDiskHash(entry, disk);
        if (current === undefined) continue;
        if (current === entry.hash) removable.push(entry);
        else plan.notices.push({ path, message: entry.key === undefined ? modifiedMessage : `${entry.key}: ${modifiedMessage}` });
      }
      const previous = { previous: group };
      if (removable.some(e => e.kind === 'file')) {
        plan.writes.push({ path, action: 'remove', ...previous });
        continue;
      }

      let text = disk;
      // Only a file the kit created is its to tidy: empty objects and an empty document are the user's otherwise.
      const created = group.some(e => e.kind === 'json-keys' && e.createdFile === true);
      const pointers: string[][] = [];
      for (const entry of removable) {
        if (entry.kind === 'md-block') text = removeMdBlock(text);
        else if (entry.kind === 'line-block') text = removeLineBlock(text);
        else if (entry.kind === 'toml-block') text = removeTomlBlock(text);
        else if (entry.kind === 'json-keys') pointers.push((entry.key ?? '').split('/'));
      }
      if (pointers.length > 0) text = removeJsonKeys(text, pointers, path, { pruneEmpty: created });
      if (text === disk) continue;

      const empty =
        text === '' || (pointers.length > 0 && created && Object.keys(parseJsonObject(text, path)).length === 0);
      plan.writes.push(
        empty ? { path, action: 'remove', ...previous } : { path, action: 'update', content: text, ...previous },
      );
    } catch (error) {
      plan.errors.push({ path, message: messageOf(error) });
      plan.carried.push(...group);
    }
  }
  return plan;
}

/**
 * Removes every manifest entry whose content on disk still matches its hash; the rest is kept and
 * reported. The manifest is removed last, and only when every file was dealt with: after an error
 * it stays, holding the entries that are still on disk.
 */
export function planUninstall(fs: RepoFs, manifest: Manifest): ApplyPlan {
  const removal = planRemovals(manifest.entries, fs, MODIFIED_KEPT);
  const writes = removal.writes;
  if (removal.errors.length === 0) writes.push({ path: MANIFEST_PATH, action: 'remove' });
  return {
    writes,
    notices: removal.notices,
    errors: removal.errors,
    manifest: { version: 1, kit: manifest.kit, entries: sortEntries(removal.carried) },
    obsolete: [],
  };
}

// --- applyPlan ------------------------------------------------------------------------------------

/** Directories the kit may have created; an empty one below (or at) these is removed with its files. */
const PRUNABLE_ROOTS = ['.claude/agents', '.claude/skills', '.codex/agents', '.gemini/agents', '.agents/skills', '.sdlc'];

const parentOf = (path: string): string => path.slice(0, Math.max(0, path.lastIndexOf('/')));

function pruneEmptyDirectories(fs: RepoFs, removedPaths: string[]): void {
  for (const path of removedPaths) {
    let dir = parentOf(path);
    while (dir !== '' && PRUNABLE_ROOTS.some(root => dir === root || dir.startsWith(`${root}/`))) {
      try {
        if (fs.list(dir, 1).length > 0) break;
        fs.remove(dir);
      } catch {
        break;
      }
      dir = parentOf(dir);
    }
  }
}

/**
 * Performs the plan. An error on one file never stops the others; each is reported in
 * `ApplyResult.errors`, and the manifest keeps the entries of whatever could not be written.
 * Obsolete entries are removed only with `removeObsolete`, and only while their content is
 * unmodified. The manifest is written (or, for an uninstall, removed) last.
 */
export function applyPlan(plan: ApplyPlan, fs: RepoFs, opts: { removeObsolete: boolean }): ApplyResult {
  const errors: PlanError[] = [...plan.errors];
  const notices: Notice[] = [...plan.notices];
  const written: string[] = [];
  const removed: string[] = [];
  const failedPaths = new Map<string, ManifestEntry[]>();
  const stillManaged: ManifestEntry[] = [];
  let removesManifest = false;

  const perform = (write: PlannedWrite): boolean => {
    try {
      if (write.action === 'remove') {
        fs.remove(write.path);
        removed.push(write.path);
      } else {
        fs.write(write.path, write.content ?? '', write.mode);
        written.push(write.path);
      }
      return true;
    } catch (error) {
      errors.push({ path: write.path, message: messageOf(error) });
      return false;
    }
  };

  for (const write of plan.writes) {
    if (write.path === MANIFEST_PATH && write.action === 'remove') removesManifest = true;
    else if (!perform(write)) failedPaths.set(write.path, write.previous ?? []);
  }

  if (!opts.removeObsolete) {
    stillManaged.push(...plan.obsolete);
  } else if (plan.obsolete.length > 0) {
    const removal = planRemovals(plan.obsolete, fs, OBSOLETE_MODIFIED);
    notices.push(...removal.notices);
    errors.push(...removal.errors);
    stillManaged.push(...removal.carried);
    for (const write of removal.writes) {
      if (!perform(write)) stillManaged.push(...(write.previous ?? []));
    }
  }

  const entries = [
    ...plan.manifest.entries.filter(e => !failedPaths.has(e.path)),
    ...[...failedPaths.values()].flat(),
    ...stillManaged,
  ];
  const manifest: Manifest = { version: 1, kit: plan.manifest.kit, entries: sortEntries(entries) };
  try {
    if (removesManifest && manifest.entries.length === 0) {
      fs.remove(MANIFEST_PATH);
      removed.push(MANIFEST_PATH);
    } else {
      const text = serializeManifest(manifest);
      if (fs.read(MANIFEST_PATH) !== text) fs.write(MANIFEST_PATH, text);
    }
  } catch (error) {
    errors.push({ path: MANIFEST_PATH, message: messageOf(error) });
  }

  pruneEmptyDirectories(fs, removed);
  return {
    written,
    removed: removed.filter(p => p !== MANIFEST_PATH),
    notices,
    errors,
    manifest,
  };
}

// --- formatPlan -----------------------------------------------------------------------------------

/**
 * The plan as text: `create|update|remove <path>`, `keep <path> (<reason>)`, `error <path>: <message>`
 * and a last line, `N changes` or `Everything is up to date`. Pass `removeObsolete` when the plan will
 * be applied with it, so obsolete entries are listed as removals instead of as kept.
 */
export function formatPlan(plan: ApplyPlan, dryRun: boolean, opts: { removeObsolete?: boolean } = {}): string {
  const lines: string[] = plan.writes.map(w => `${w.action} ${w.path}`);
  let changes = plan.writes.length;
  for (const entry of plan.obsolete) {
    const what = entry.key === undefined ? '' : `${entry.key} `;
    if (opts.removeObsolete) {
      changes += 1;
      lines.push(
        entry.kind === 'file'
          ? `remove ${entry.path} (${NO_LONGER_GENERATED})`
          : `update ${entry.path} (${NO_LONGER_GENERATED}: ${what || 'managed block '}removed)`,
      );
    } else {
      lines.push(`keep ${entry.path} (${what}${NO_LONGER_GENERATED}; run sdlc upgrade to remove)`);
    }
  }
  for (const notice of plan.notices) lines.push(`keep ${notice.path} (${notice.message})`);
  for (const error of plan.errors) lines.push(`error ${error.path}: ${error.message}`);

  if (changes === 0 && plan.errors.length === 0) lines.push('Everything is up to date');
  else {
    const noun = changes === 1 ? 'change' : 'changes';
    lines.push(`${changes} ${noun}${dryRun ? ' (dry run: nothing written)' : ''}`);
  }
  return lines.join('\n');
}
